LAUSpectralTableWidget::LAUSpectralTableWidget(QWidget *parent) : QWidget(parent)
{
    this->setLayout(new QVBoxLayout);
    this->layout()->setContentsMargins(0, 0, 0, 0);

    table = new QTableWidget();
    this->layout()->addWidget(table);

    table->setRowCount(2);
    table->setColumnCount(37);

    QStringList headers;
    headers << QString("Label");
    for (int n = 0; n < 36; n++) {
        headers << QString("%1").arg(10 * n + 380);
    }
    table->setHorizontalHeaderLabels(headers);

    for (int n = 0; n < table->rowCount(); n++) {
        table->setRowHeight(n, 20);
    }

    for (int n = 1; n < table->columnCount(); n++) {
        table->setColumnWidth(n, 60);
    }
}

